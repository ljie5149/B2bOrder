namespace B2bOrder.Resources.eCommerce
{
    /// <summary>
    /// InventoryDB V2 Shared Core Schema
    /// 設計目標：
    /// 1. 同時支援 Shopping Platform 與 Construction ERP
    /// 2. 支援庫存帳、異動、預留、批號、序號、調撥、盤點、報廢、領料、退料與材料耗用
    /// 3. 倉庫與儲位由 MasterDB 提供；Item與變體由 PIM/MIMDB 提供
    /// 4. 採購收貨由 PurchaseDB 提供；銷售與訂單由 Shopping/OMS/SalesDB 提供
    /// 5. 專案、工地、WBS、成本中心與承包商等維度皆以 sid 關聯
    /// 6. nid：資料庫內部主鍵；sid：跨服務/API 對外識別碼
    /// 7. avalible：Y可用；W停用；D刪除
    /// 8. 適用 MySQL 8.x / InnoDB / utf8mb4
    /// </summary>
    internal static class InventoryDB
    {
        public static readonly string CreateTables = @"
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- =========================================================
-- 01. 庫存政策與Item庫存設定
-- =========================================================

CREATE TABLE IF NOT EXISTS inv_policy (
    nid                     BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY COMMENT '流水號',
    sid                     VARCHAR(32)                         NOT NULL UNIQUE COMMENT '庫存政策序號',
    create_date             DATETIME                            NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '建立日期',
    modify_date             DATETIME                                NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT '修改日期',
    policy_code             VARCHAR(100)                        NOT NULL COMMENT '政策代碼',
    policy_name             VARCHAR(200)                        NOT NULL COMMENT '政策名稱',
    company_sid             VARCHAR(32)                             NULL COMMENT 'MasterDB公司序號',
    warehouse_sid           VARCHAR(32)                             NULL COMMENT 'MasterDB倉庫序號',
    negative_stock_allowed  TINYINT(1)                          NOT NULL DEFAULT 0 COMMENT '是否允許負庫存',
    reservation_required    TINYINT(1)                          NOT NULL DEFAULT 1 COMMENT '出庫是否需先預留',
    batch_strategy          VARCHAR(30)                         NOT NULL DEFAULT 'FIFO' COMMENT 'FIFO先進先出;FEFO先到期先出;LIFO後進先出;MANUAL人工',
    cost_method             VARCHAR(30)                         NOT NULL DEFAULT 'MOVING_AVERAGE' COMMENT 'MOVING_AVERAGE移動平均;STANDARD標準;FIFO;SPECIFIC特定辨認',
    over_issue_rate         DECIMAL(8,4)                        NOT NULL DEFAULT 0 COMMENT '允許超領率百分比',
    short_issue_rate        DECIMAL(8,4)                        NOT NULL DEFAULT 0 COMMENT '允許短領率百分比',
    policy_status           VARCHAR(20)                         NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE啟用;INACTIVE停用',
    avalible                VARCHAR(2)                          NOT NULL DEFAULT 'Y' COMMENT 'Y可用;D刪除;W停用',
    remark                  TEXT                                    NULL COMMENT '備註',
    CONSTRAINT uk_ip_policy_code UNIQUE (policy_code),
    INDEX idx_ip_company_sid (company_sid),
    INDEX idx_ip_warehouse_sid (warehouse_sid),
    INDEX idx_ip_status (policy_status),
    INDEX idx_ip_avalible (avalible),
    CHECK (over_issue_rate >= 0),
    CHECK (short_issue_rate >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='庫存管理政策';

CREATE TABLE IF NOT EXISTS inv_item_setting (
    nid                     BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY COMMENT '流水號',
    sid                     VARCHAR(32)                         NOT NULL UNIQUE COMMENT 'Item庫存設定序號',
    create_date             DATETIME                            NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '建立日期',
    modify_date             DATETIME                                NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT '修改日期',
    item_sid                VARCHAR(32)                         NOT NULL COMMENT 'PIM/MIMDB Item序號',
    variant_sid             VARCHAR(32)                             NULL COMMENT 'PIM/MIMDB變體序號',
    company_sid             VARCHAR(32)                             NULL COMMENT 'MasterDB公司序號',
    inventory_unit_sid      VARCHAR(32)                         NOT NULL COMMENT 'MasterDB庫存單位序號',
    issue_unit_sid          VARCHAR(32)                             NULL COMMENT 'MasterDB發料單位序號',
    receipt_unit_sid        VARCHAR(32)                             NULL COMMENT 'MasterDB收料單位序號',
    batch_control           TINYINT(1)                          NOT NULL DEFAULT 0 COMMENT '是否批號控管',
    serial_control          TINYINT(1)                          NOT NULL DEFAULT 0 COMMENT '是否序號控管',
    expiry_control          TINYINT(1)                          NOT NULL DEFAULT 0 COMMENT '是否效期控管',
    quality_hold_required   TINYINT(1)                          NOT NULL DEFAULT 0 COMMENT '收貨後是否先進待驗',
    safety_stock_qty        DECIMAL(20,6)                       NOT NULL DEFAULT 0 COMMENT '安全庫存',
    reorder_point_qty       DECIMAL(20,6)                       NOT NULL DEFAULT 0 COMMENT '再訂購點',
    reorder_qty             DECIMAL(20,6)                       NOT NULL DEFAULT 0 COMMENT '建議補貨量',
    maximum_stock_qty       DECIMAL(20,6)                           NULL COMMENT '最大庫存',
    minimum_issue_qty       DECIMAL(20,6)                       NOT NULL DEFAULT 0 COMMENT '最小發料量',
    issue_multiple_qty      DECIMAL(20,6)                       NOT NULL DEFAULT 1 COMMENT '發料倍數',
    setting_status          VARCHAR(20)                         NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE啟用;INACTIVE停用',
    avalible                VARCHAR(2)                          NOT NULL DEFAULT 'Y' COMMENT 'Y可用;D刪除;W停用',
    remark                  TEXT                                    NULL COMMENT '備註',
    CONSTRAINT uk_iis_item_variant_company UNIQUE (item_sid, variant_sid, company_sid),
    INDEX idx_iis_item_sid (item_sid),
    INDEX idx_iis_variant_sid (variant_sid),
    INDEX idx_iis_company_sid (company_sid),
    INDEX idx_iis_status (setting_status),
    INDEX idx_iis_avalible (avalible),
    CHECK (safety_stock_qty >= 0),
    CHECK (reorder_point_qty >= 0),
    CHECK (reorder_qty >= 0),
    CHECK (maximum_stock_qty IS NULL OR maximum_stock_qty >= 0),
    CHECK (minimum_issue_qty >= 0),
    CHECK (issue_multiple_qty > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Item庫存控制設定';

-- =========================================================
-- 02. 即時庫存帳
-- =========================================================

