    INDEX idx_isb_variant_sid (variant_sid),
    INDEX idx_isb_batch_sid (batch_sid),
    INDEX idx_isb_project_sid (project_sid),
    INDEX idx_isb_site_sid (site_sid),
    INDEX idx_isb_wbs_sid (wbs_sid),
    INDEX idx_isb_owner_party_sid (owner_party_sid),
    INDEX idx_isb_stock_status (stock_status),
    INDEX idx_isb_last_movement_date (last_movement_date),
    CHECK (on_hand_qty >= 0),
    CHECK (reserved_qty >= 0),
    CHECK (allocated_qty >= 0),
    CHECK (available_qty >= 0),
    CHECK (in_transit_qty >= 0),
    CHECK (quality_hold_qty >= 0),
    CHECK (blocked_qty >= 0),
    CHECK (damaged_qty >= 0),
    CHECK (average_cost >= 0),
    CHECK (total_cost >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='即時庫存餘額';

CREATE TABLE IF NOT EXISTS inv_stock_summary (
