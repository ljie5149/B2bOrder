    manufacture_date        DATE                                    NULL COMMENT '製造日期',
    expiry_date             DATE                                    NULL COMMENT '有效期限',
    receipt_sid             VARCHAR(32)                             NULL COMMENT '來源收貨單序號',
    inspection_sid          VARCHAR(32)                             NULL COMMENT '來源驗收單序號',
    quality_status          VARCHAR(20)                         NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING待驗;PASS合格;FAIL不合格;CONDITIONAL有條件;EXPIRED過期',
    batch_status            VARCHAR(20)                         NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE有效;BLOCKED凍結;CONSUMED用罄;EXPIRED過期;RECALLED召回',
    avalible                VARCHAR(2)                          NOT NULL DEFAULT 'Y' COMMENT 'Y可用;D刪除;W停用',
    remark                  TEXT                                    NULL COMMENT '備註',
    CONSTRAINT uk_ib_item_variant_batch UNIQUE (item_sid, variant_sid, batch_no),
    INDEX idx_ib_item_sid (item_sid),
    INDEX idx_ib_variant_sid (variant_sid),
    INDEX idx_ib_supplier_party_sid (supplier_party_sid),
    INDEX idx_ib_manufacturer_party_sid (manufacturer_party_sid),
    INDEX idx_ib_expiry_date (expiry_date),
    INDEX idx_ib_quality_status (quality_status),
    INDEX idx_ib_batch_status (batch_status),
    INDEX idx_ib_avalible (avalible),
