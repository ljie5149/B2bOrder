    INDEX idx_it_transaction_type (transaction_type),
    INDEX idx_it_transaction_date (transaction_date),
    INDEX idx_it_company_sid (company_sid),
    INDEX idx_it_warehouse_sid (warehouse_sid),
    INDEX idx_it_location_sid (location_sid),
    INDEX idx_it_item_sid (item_sid),
    INDEX idx_it_variant_sid (variant_sid),
    INDEX idx_it_batch_sid (batch_sid),
    INDEX idx_it_serial_sid (serial_sid),
    INDEX idx_it_project_sid (project_sid),
    INDEX idx_it_site_sid (site_sid),
    INDEX idx_it_wbs_sid (wbs_sid),
    INDEX idx_it_source (source_type, source_sid),
    INDEX idx_it_correlation_id (correlation_id),
    CHECK (quantity > 0),
    CHECK (unit_cost >= 0),
    CHECK (total_cost >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='不可變庫存異動流水帳';

CREATE TABLE IF NOT EXISTS inv_cost_layer (
    nid                     BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY COMMENT '流水號',
    sid                     VARCHAR(32)                         NOT NULL UNIQUE COMMENT '成本層序號',
    create_date             DATETIME                            NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '建立日期',
    company_sid             VARCHAR(32)                         NOT NULL COMMENT '公司序號',
    warehouse_sid           VARCHAR(32)                         NOT NULL COMMENT '倉庫序號',
    item_sid                VARCHAR(32)                         NOT NULL COMMENT 'Item序號',
    variant_sid             VARCHAR(32)                             NULL COMMENT '變體序號',
    batch_sid               VARCHAR(32)                             NULL COMMENT '批號序號',
    source_transaction_sid  VARCHAR(32)                         NOT NULL COMMENT '來源入庫異動序號',
    original_qty            DECIMAL(20,6)                       NOT NULL COMMENT '原始數量',
    remaining_qty           DECIMAL(20,6)                       NOT NULL COMMENT '剩餘數量',
    unit_cost               DECIMAL(20,6)                       NOT NULL COMMENT '單位成本',
    currency_sid            VARCHAR(32)                         NOT NULL COMMENT '幣別序號',
    exchange_rate           DECIMAL(20,10)                      NOT NULL DEFAULT 1 COMMENT '匯率',
    cost_date               DATETIME                            NOT NULL COMMENT '成本日期',
    layer_status            VARCHAR(20)                         NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN可用;PARTIAL部分使用;CLOSED用罄;ADJUSTED已調整',
    INDEX idx_icl_company_sid (company_sid),
    INDEX idx_icl_warehouse_sid (warehouse_sid),
    INDEX idx_icl_item_sid (item_sid),
    INDEX idx_icl_variant_sid (variant_sid),
    INDEX idx_icl_batch_sid (batch_sid),
    INDEX idx_icl_source_transaction_sid (source_transaction_sid),
    INDEX idx_icl_cost_date (cost_date),
    INDEX idx_icl_status (layer_status),
    CHECK (original_qty > 0),
    CHECK (remaining_qty >= 0),
    CHECK (remaining_qty <= original_qty),
    CHECK (unit_cost >= 0),
    CHECK (exchange_rate > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='FIFO與特定辨認成本層';

