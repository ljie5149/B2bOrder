    source_line_sid         VARCHAR(32)                             NULL COMMENT '來源明細序號',
    operator_user_sid       VARCHAR(32)                             NULL COMMENT '操作人員序號',
    correlation_id          VARCHAR(100)                            NULL COMMENT '跨服務關聯識別碼',
