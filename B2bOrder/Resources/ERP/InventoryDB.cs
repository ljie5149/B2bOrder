-- =========================================================
-- 04. 庫存異動與成本
-- =========================================================

CREATE TABLE IF NOT EXISTS inv_transaction (
    nid                     BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY COMMENT '流水號',
    sid                     VARCHAR(32)                         NOT NULL UNIQUE COMMENT '庫存異動序號',
    create_date             DATETIME                            NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '建立日期',
    transaction_no          VARCHAR(100)                        NOT NULL COMMENT '異動編號',
    transaction_type        VARCHAR(30)                         NOT NULL COMMENT 'RECEIPT入庫;ISSUE出庫;TRANSFER_IN調入;TRANSFER_OUT調出;ADJUST_IN調增;ADJUST_OUT調減;RETURN_IN退料入庫;RETURN_OUT退貨出庫;CONSUME耗用;SCRAP報廢',
    transaction_date        DATETIME                            NOT NULL COMMENT '異動時間',
    company_sid             VARCHAR(32)                         NOT NULL COMMENT '公司序號',
    warehouse_sid           VARCHAR(32)                         NOT NULL COMMENT '倉庫序號',
    location_sid            VARCHAR(32)                         NOT NULL COMMENT '儲位序號',
    item_sid                VARCHAR(32)                         NOT NULL COMMENT 'Item序號',
    variant_sid             VARCHAR(32)                             NULL COMMENT '變體序號',
    batch_sid               VARCHAR(32)                             NULL COMMENT '批號序號',
    serial_sid              VARCHAR(32)                             NULL COMMENT '序號序號',
    quantity                DECIMAL(20,6)                       NOT NULL COMMENT '異動數量',
    unit_sid                VARCHAR(32)                         NOT NULL COMMENT '單位序號',
    unit_cost               DECIMAL(20,6)                       NOT NULL DEFAULT 0 COMMENT '單位成本',
    total_cost              DECIMAL(20,4)                       NOT NULL DEFAULT 0 COMMENT '總成本',
    stock_status_from       VARCHAR(20)                             NULL COMMENT '原庫存狀態',
    stock_status_to         VARCHAR(20)                             NULL COMMENT '新庫存狀態',
    project_sid             VARCHAR(32)                             NULL COMMENT '專案序號',
    site_sid                VARCHAR(32)                             NULL COMMENT '工地序號',
    wbs_sid                 VARCHAR(32)                             NULL COMMENT 'WBS序號',
    cost_center_sid         VARCHAR(32)                             NULL COMMENT '成本中心序號',
    owner_party_sid         VARCHAR(32)                             NULL COMMENT '庫存所有Party序號',
    source_type             VARCHAR(50)                         NOT NULL COMMENT 'PURCHASE_RECEIPT採購收貨;SALES_ORDER銷售訂單;OMS;TRANSFER調撥;COUNT盤點;ISSUE_REQUEST領料;RETURN退料;MANUAL人工;OTHER',
