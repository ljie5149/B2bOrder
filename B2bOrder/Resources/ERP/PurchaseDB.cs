    workflow_instance_sid   VARCHAR(32)                             NULL COMMENT 'WorkflowDB流程實例序號',
    avalible                VARCHAR(2)                          NOT NULL DEFAULT 'Y' COMMENT 'Y可用;D刪除;W停用',
    remark                  TEXT                                    NULL COMMENT '備註',
    CONSTRAINT uk_prfq_rfq_no UNIQUE (rfq_no),
    INDEX idx_prfq_company_sid (company_sid),
    INDEX idx_prfq_project_sid (project_sid),
    INDEX idx_prfq_purchase_type_sid (purchase_type_sid),
    INDEX idx_prfq_requisition_sid (requisition_sid),
    INDEX idx_prfq_issue_date (issue_date),
    INDEX idx_prfq_response_deadline (response_deadline),
    INDEX idx_prfq_status (rfq_status),
    INDEX idx_prfq_avalible (avalible),
