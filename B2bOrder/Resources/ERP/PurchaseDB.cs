namespace B2bOrder.Resources.eCommerce
{
    /// <summary>
    /// PurchaseDB V2 Shared Core Schema
    /// 設計目標：
    /// 1. 同時支援 Shopping Platform 與 Construction ERP
    /// 2. 支援請購、詢價、比價、採購單、交期、收貨、驗收、退貨與供應商績效
    /// 3. 預留公司、營運單位、部門、專案、成本中心、倉庫、工地、WBS、預算與合約維度
    /// 4. PartyDB 管理供應商與承包商；PIM/MIMDB 管理商品、材料、設備與服務
    /// 5. PricingDB 管理協議價與採購價格；InventoryDB 管理實際庫存
    /// 6. AccountingDB 管理應付帳款；WorkflowDB 管理簽核流程
    /// 7. nid：資料庫內部主鍵；sid：跨服務/API 對外識別碼
    /// 8. avalible：Y可用；W停用；D刪除
    /// 9. 適用 MySQL 8.x / InnoDB / utf8mb4
    /// </summary>
    internal static class PurchaseDB
    {
        public static readonly string CreateTables = @"
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- =========================================================
-- 01. 採購類型與政策
-- =========================================================

CREATE TABLE IF NOT EXISTS pur_purchase_type (
    nid                     BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY COMMENT '流水號',
    sid                     VARCHAR(32)                         NOT NULL UNIQUE COMMENT '採購類型序號',
    create_date             DATETIME                            NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '建立日期',
    modify_date             DATETIME                                NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT '修改日期',
    purchase_type_code      VARCHAR(100)                        NOT NULL COMMENT '採購類型代碼',
    purchase_type_name      VARCHAR(200)                        NOT NULL COMMENT '採購類型名稱',
    purchase_category       VARCHAR(30)                         NOT NULL COMMENT 'MATERIAL材料;PRODUCT商品;EQUIPMENT設備;SERVICE服務;LABOR勞務;RENTAL租賃;SUBCONTRACT發包;GENERAL一般',
    approval_required       TINYINT(1)                          NOT NULL DEFAULT 1 COMMENT '是否需要簽核',
    receipt_required        TINYINT(1)                          NOT NULL DEFAULT 1 COMMENT '是否需要收貨',
    inspection_required     TINYINT(1)                          NOT NULL DEFAULT 0 COMMENT '是否需要驗收',
    inventory_effect        TINYINT(1)                          NOT NULL DEFAULT 1 COMMENT '是否影響庫存',
    contract_required       TINYINT(1)                          NOT NULL DEFAULT 0 COMMENT '是否需合約',
    budget_check_required   TINYINT(1)                          NOT NULL DEFAULT 0 COMMENT '是否需預算檢核',
    type_status             VARCHAR(20)                         NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE啟用;INACTIVE停用',
    avalible                VARCHAR(2)                          NOT NULL DEFAULT 'Y' COMMENT 'Y可用;D刪除;W停用',
    remark                  TEXT                                    NULL COMMENT '備註',
    CONSTRAINT uk_ppt_purchase_type_code UNIQUE (purchase_type_code),
    INDEX idx_ppt_category (purchase_category),
    INDEX idx_ppt_approval_required (approval_required),
    INDEX idx_ppt_budget_check_required (budget_check_required),
    INDEX idx_ppt_status (type_status),
    INDEX idx_ppt_avalible (avalible)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='採購類型';

CREATE TABLE IF NOT EXISTS pur_policy (
