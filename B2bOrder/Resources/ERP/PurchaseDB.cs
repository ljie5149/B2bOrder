    policy_status           VARCHAR(20)                         NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE啟用;INACTIVE停用',
    avalible                VARCHAR(2)                          NOT NULL DEFAULT 'Y' COMMENT 'Y可用;D刪除;W停用',
    remark                  TEXT                                    NULL COMMENT '備註',
    CONSTRAINT uk_pp_policy_code UNIQUE (policy_code),
    INDEX idx_pp_company_sid (company_sid),
    INDEX idx_pp_purchase_type_sid (purchase_type_sid),
    INDEX idx_pp_status (policy_status),
    INDEX idx_pp_avalible (avalible),
