    CHECK (approval_amount IS NULL OR approval_amount >= 0),
    CHECK (tender_amount IS NULL OR tender_amount >= 0),
    CHECK (over_receipt_rate >= 0),
    CHECK (under_receipt_rate >= 0),
    CHECK (price_variance_rate >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='採購政策';

