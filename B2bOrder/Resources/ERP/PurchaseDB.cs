    CHECK (estimated_amount >= 0),
    CHECK (ordered_qty >= 0),
    CHECK (cancelled_qty >= 0),
    CHECK (ordered_qty + cancelled_qty <= quantity)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='採購請購明細';

